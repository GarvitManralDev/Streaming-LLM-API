import asyncio


async def fake_llm_call(
    message: str,
    temperature: float = 0.7
) -> str:
    """
    Simulate a normal LLM API call.

    We use asyncio.sleep() so beginners can understand
    the FastAPI architecture without needing a paid LLM.
    """

    # Simulate network/model delay.
    await asyncio.sleep(2)

    return (
        f"Here is a beginner-friendly answer for: '{message}'. "
        f"This response is generated by our demo LLM service. "
        f"In a real project, this function can call OpenAI, Groq, "
        f"Gemini, or another model provider."
    )


async def call_llm_with_retry(
    message: str,
    temperature: float = 0.7,
    max_attempts: int = 3
) -> str:
    """
    Demonstrate where retry logic belongs.
    """

    for attempt in range(1, max_attempts + 1):
        try:
            return await fake_llm_call(
                message=message,
                temperature=temperature
            )

        except Exception:
            # Final attempt failed? Stop retrying.
            if attempt == max_attempts:
                raise

            # Wait briefly before trying again.
            await asyncio.sleep(1)


async def stream_llm_words(message: str):
    """
    Simulate streaming tokens/words from an LLM.
    """

    answer = (
        f"You asked: {message}. "
        "This answer is being streamed word by word. "
        "In production, these chunks can come directly "
        "from a streaming LLM API."
    )

    for word in answer.split():

        # Small delay so the streaming is visible.
        await asyncio.sleep(0.12)

        # SSE format:
        # data: something
        #
        yield f"data: {word} \n\n"

    # Custom completion event.
    yield "event: done\ndata: completed\n\n"
